/** Срок, через который адрес удалённого аккаунта снова можно зарегистрировать (Арх. 10.5), суток. */
export const REREGISTER_COOLDOWN_DAYS_DEFAULT = 30

/**
 * Строка диалога удаления о карантине адреса. Срок называется числом (Арх. 11.7, п. 4): по умолчанию 30 дней,
 * но на стенде он может быть короче суток (`REREGISTER_COOLDOWN_DAYS` — дробное число), тогда — в часах или минутах.
 */
export function deleteDialogDelay(days: number): string {
  if (!Number.isFinite(days) || days <= 0) return 'Зарегистрироваться на этот адрес снова можно будет сразу.'
  const minutes = days * 24 * 60
  const period =
    days >= 1
      ? pluralize(Math.round(days), PLURALS.day)
      : minutes >= 60
        ? pluralize(Math.round(minutes / 60), PLURALS.hour)
        : pluralize(Math.max(1, Math.round(minutes)), ['минуту', 'минуты', 'минут'])
  return `Зарегистрироваться на этот адрес снова можно будет через ${period}.`
}
